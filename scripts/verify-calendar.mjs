let roundTrips = 0;
for (let year = 1446; year <= 1449; year++) for (let month = 1; month <= 12; month++) {
  const length = daysInMonth(year, month, 'hijri'); assert([29, 30].includes(length));
  for (const day of [1, length]) {
    const iso = fromCalendar({ year, month, day }, 'hijri');
    assert.deepEqual(calendarParts(iso, 'hijri'), { year, month, day }); roundTrips++;
  }
  assert.equal(fromCalendar({ year, month, day: length + 1 }, 'hijri'), '');
  const first = fromCalendar({ year, month, day: 1 }, 'hijri');
  const range = monthRange(first, 'hijri');
  assert.equal(shiftDays(range.end, 1), range.nextStart);
  const grid = calendarMonthGrid(first, 'hijri');
  assert.equal(grid.length, 42); assert.equal(dateObject(grid[0].date).getUTCDay(), 0);
  assert.equal(grid.filter(cell => !cell.outside).length, length);
  grid.forEach((cell, index) => {
    assert.equal(cell.date, shiftDays(grid[0].date, index));
    assert.equal(cell.day, calendarParts(cell.date, 'hijri').day);
  });
  const next = calendarParts(moveCalendarMonth(range.end, 1, 'hijri'), 'hijri');
  assert.equal(next.month, month === 12 ? 1 : month + 1);
  assert.equal(next.year, month === 12 ? year + 1 : year);
  assert.equal(next.day, Math.min(length, daysInMonth(next.year, next.month, 'hijri')));
}

